    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {
        StringBuilder sb = new StringBuilder();
        try {
            ProductController controller = new ProductController();
            List<Product> products = controller.getAll();
            for (Product p : products) {
                if (p.getQuantity() < 5) {
                    sb.append(p.getId()).append(" - ").append(p.getName()).append(" (").append(p.getQuantity()).append(")").append("\n");
                }
            }
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        if (sb.length() == 0) {
            jTextArea1.setText("No restock alerts");
        } else {
            jTextArea1.setText(sb.toString());
        }
    }
    
