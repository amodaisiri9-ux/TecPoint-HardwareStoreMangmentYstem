private void loadProducts() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"ID","Name","Category","Price","Quantity"}, 0
        );
        try {
            ProductController controller = new ProductController();
            java.util.List<Product> products = controller.getAll();
            for (Product p : products) {
                model.addRow(new Object[]{
                    p.getId(), p.getName(), p.getCategory(), p.getPrice(), p.getQuantity()
                });
            }
            jTable1.setModel(model);
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

