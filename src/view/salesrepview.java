    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {
        String query = jTextField1.getText().trim();
        if (query.isEmpty()) {
            loadProducts();
            return;
        }
        ProductController controller = new ProductController();
        try {
            try {
                int id = Integer.parseInt(query);
                Product p = controller.getById(id);
                if (p != null) {
                    DefaultTableModel model = new DefaultTableModel(new Object[]{"ID","Name","Category","Price","Quantity"}, 0);
                    model.addRow(new Object[]{p.getId(), p.getName(), p.getCategory(), p.getPrice(), p.getQuantity()});
                    jTable1.setModel(model);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Not found");
                }
            } catch (NumberFormatException nf) {
                String pattern = "%" + query + "%";
                java.util.List<Product> products = controller.findByNameLike(pattern);
                DefaultTableModel model = new DefaultTableModel(new Object[]{"ID","Name","Category","Price","Quantity"}, 0);
                for (Product p : products) {
                    model.addRow(new Object[]{p.getId(), p.getName(), p.getCategory(), p.getPrice(), p.getQuantity()});
                }
                jTable1.setModel(model);
            }
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void loadProducts() {
        DefaultTableModel model = new DefaultTableModel(new Object[]{"ID","Name","Category","Price","Quantity"}, 0);
        try {
            ProductController controller = new ProductController();
            List<Product> products = controller.getAll();
            for (Product p : products) {
                model.addRow(new Object[]{p.getId(), p.getName(), p.getCategory(), p.getPrice(), p.getQuantity()});
            }
            jTable1.setModel(model);
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        javax.swing.JTextField nameField = new javax.swing.JTextField();
        javax.swing.JTextField categoryField = new javax.swing.JTextField();
        javax.swing.JTextField priceField = new javax.swing.JTextField();
        javax.swing.JTextField qtyField = new javax.swing.JTextField();
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 2));
        panel.add(new javax.swing.JLabel("Name"));
        panel.add(nameField);
        panel.add(new javax.swing.JLabel("Category"));
        panel.add(categoryField);
        panel.add(new javax.swing.JLabel("Price"));
        panel.add(priceField);
        panel.add(new javax.swing.JLabel("Quantity"));
        panel.add(qtyField);
        int result = javax.swing.JOptionPane.showConfirmDialog(this, panel, "Add Product", javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.PLAIN_MESSAGE);
        if (result == javax.swing.JOptionPane.OK_OPTION) {
            String name = nameField.getText().trim();
            String category = categoryField.getText().trim();
            String priceText = priceField.getText().trim();
            String qtyText = qtyField.getText().trim();
            if (name.isEmpty() || category.isEmpty() || priceText.isEmpty() || qtyText.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Fill all fields");
                return;
            }
            double price;
            int qty;
            try {
                price = Double.parseDouble(priceText);
                qty = Integer.parseInt(qtyText);
            } catch (NumberFormatException nfe) {
                javax.swing.JOptionPane.showMessageDialog(this, "Invalid values");
                return;
            }
            Product p = new Product(0, name, category, price, qty);
            try {
                ProductController controller = new ProductController();
                boolean ok = controller.add(p);
                if (ok) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Added");
                    loadProducts();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Add failed");
                }
            } catch (SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    
