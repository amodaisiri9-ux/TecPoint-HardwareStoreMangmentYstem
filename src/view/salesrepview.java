    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a row to delete");
            return;
        }
        Object idObj = jTable1.getModel().getValueAt(row, 0);
        int id;
        try {
            if (idObj instanceof Number) {
                id = ((Number) idObj).intValue();
            } else {
                id = Integer.parseInt(String.valueOf(idObj));
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid ID. Please refresh.");
            return;
        }
        try {
            ProductController controller = new ProductController();
            boolean ok = controller.delete(id);
            if (ok) {
                ((DefaultTableModel) jTable1.getModel()).removeRow(row);
                javax.swing.JOptionPane.showMessageDialog(this, "Deleted");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Delete failed");
            }
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(), "DB Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

